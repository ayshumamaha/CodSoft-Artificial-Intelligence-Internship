# Tic-Tac-Toe AI using Minimax

board = [" " for _ in range(9)]

def display():
    print()
    for i in range(0, 9, 3):
        print(" " + " | ".join(board[i:i+3]))
        if i < 6:
            print("---+---+---")
    print()


def winner(player):
    combinations = [
        (0, 1, 2), (3, 4, 5), (6, 7, 8),
        (0, 3, 6), (1, 4, 7), (2, 5, 8),
        (0, 4, 8), (2, 4, 6)
    ]

    return any(
        board[a] == board[b] == board[c] == player
        for a, b, c in combinations
    )


def minimax(is_ai):
    if winner("O"):
        return 1

    if winner("X"):
        return -1

    if " " not in board:
        return 0

    if is_ai:
        best = -100

        for i in range(9):
            if board[i] == " ":
                board[i] = "O"
                score = minimax(False)
                board[i] = " "
                best = max(best, score)

        return best

    else:
        best = 100

        for i in range(9):
            if board[i] == " ":
                board[i] = "X"
                score = minimax(True)
                board[i] = " "
                best = min(best, score)

        return best


def ai_move():
    best_score = -100
    best_position = None

    for i in range(9):
        if board[i] == " ":
            board[i] = "O"
            score = minimax(False)
            board[i] = " "

            if score > best_score:
                best_score = score
                best_position = i

    if best_position is not None:
        board[best_position] = "O"


print("===== TIC-TAC-TOE AI =====")
print("You are X. Computer is O.")
print("Choose positions from 1 to 9.")

display()

while True:

    try:
        position = int(input("Enter your position (1-9): ")) - 1

        if position < 0 or position > 8 or board[position] != " ":
            print("Invalid position! Try again.")
            continue

    except ValueError:
        print("Please enter a number.")
        continue

    board[position] = "X"
    display()

    if winner("X"):
        print("Congratulations! You win!")
        break

    if " " not in board:
        print("Game Draw!")
        break

    print("Computer is thinking...")
    ai_move()
    display()

    if winner("O"):
        print("Computer wins!")
        break

    if " " not in board:
        print("Game Draw!")
        break