import cv2

print("FACE DETECTION SYSTEM")

# Load face detection model
model = cv2.data.haarcascades + "haarcascade_frontalface_default.xml"
face_detector = cv2.CascadeClassifier(model)

# Upload image path
path = input("Enter image path: ")

# Read image
image = cv2.imread(path)

if image is None:
    print("Image not found! Check the image path.")

else:
    # Convert to grayscale
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # Detect faces
    faces = face_detector.detectMultiScale(
        gray, 1.1, 4
    )

    # Draw rectangles
    for (x, y, w, h) in faces:
        cv2.rectangle(
            image, (x, y), (x+w, y+h),
            (0, 255, 0), 2
        )

    # Save result
    cv2.imwrite("detected_faces.jpg", image)

    print("Faces detected:", len(faces))
    print("Output saved as detected_faces.jpg")

    # Display image in Jupyter
    from PIL import Image
    display(Image.open("detected_faces.jpg"))