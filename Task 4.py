# Movie Recommendation System

movies = {
    "Avengers": ["Action", "Adventure", "Sci-Fi"],
    "Iron Man": ["Action", "Adventure", "Sci-Fi"],
    "Thor": ["Action", "Fantasy", "Adventure"],
    "Titanic": ["Romance", "Drama"],
    "The Notebook": ["Romance", "Drama"],
    "Joker": ["Crime", "Drama", "Thriller"],
    "Batman": ["Action", "Crime", "Drama"],
    "Interstellar": ["Sci-Fi", "Adventure", "Drama"],
    "Inception": ["Action", "Sci-Fi", "Thriller"],
    "Frozen": ["Animation", "Adventure", "Fantasy"]
}

def recommend(selected_movie):

    selected_genres = set(movies[selected_movie])

    recommendations = []

    for movie, genres in movies.items():

        if movie == selected_movie:
            continue

        common = selected_genres.intersection(set(genres))

        score = len(common)

        if score > 0:
            recommendations.append((movie, score))

    recommendations.sort(key=lambda x: x[1], reverse=True)

    return recommendations[:3]


print("===== MOVIE RECOMMENDATION SYSTEM =====")

while True:

    print("\nAvailable Movies:")

    for movie in movies:
        print("-", movie)

    choice = input("\nEnter a movie name (or exit): ").strip()

    if choice.lower() == "exit":
        print("Thank you!")
        break

    if choice not in movies:
        print("Movie not found. Please enter a valid name.")
        continue

    results = recommend(choice)

    print("\nRecommended Movies for", choice)

    if results:
        for movie, score in results:
            print("-", movie)
    else:
        print("No similar movies found.")