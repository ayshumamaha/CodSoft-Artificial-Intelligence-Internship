from transformers import BlipProcessor, BlipForConditionalGeneration
from PIL import Image
import os

print("Loading image captioning model...")
print("Please wait. First-time download may take a few minutes.")

# Load pretrained model
processor = BlipProcessor.from_pretrained(
    "Salesforce/blip-image-captioning-base"
)

model = BlipForConditionalGeneration.from_pretrained(
    "Salesforce/blip-image-captioning-base"
)

print("\nImage Captioning Model Loaded Successfully!")

while True:

    path = input("\nEnter image path (or type exit): ").strip()

    if path.lower() == "exit":
        print("Program ended.")
        break

    if not os.path.isfile(path):
        print("Image file not found. Please try again.")
        continue

    try:
        # Open image
        image = Image.open(path).convert("RGB")

        # Prepare image for model
        inputs = processor(
            images=image,
            return_tensors="pt"
        )

        # Generate caption
        output = model.generate(
            **inputs,
            max_new_tokens=50
        )

        caption = processor.decode(
            output[0],
            skip_special_tokens=True
        )

        print("\nGenerated Caption:")
        print(caption)

    except Exception as e:
        print("Unable to process image:", e)