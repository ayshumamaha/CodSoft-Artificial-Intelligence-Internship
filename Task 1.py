print("===== RULE-BASED CHATBOT =====")
print("Hello! I am your chatbot.")
print("Type 'exit' to stop the conversation.")

while True:

    user = input("\nYou: ").lower().strip()

    if user == "exit":
        print("Bot: Goodbye! Have a nice day.")
        break

    elif "hello" in user or "hi" in user:
        print("Bot: Hello! How can I help you?")

    elif "your name" in user:
        print("Bot: I am a simple Python chatbot.")

    elif "how are you" in user:
        print("Bot: I am doing great! Thank you.")

    elif "python" in user:
        print("Bot: Python is a popular programming language.")

    elif "machine learning" in user:
        print("Bot: Machine learning helps computers learn from data.")

    elif "help" in user:
        print("Bot: Sure! Ask me about Python or machine learning.")

    elif "thank" in user:
        print("Bot: You're welcome!")

    elif "bye" in user:
        print("Bot: Goodbye!")
        break

    else:
        print("Bot: Sorry, I don't understand. Please ask something else.")